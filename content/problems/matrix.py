'''
Задачи на матрицы — списки списков: обход по строкам и по столбцам, суммы, подсчёты и поиск.

Во всех задачах матрица прямоугольная: в каждой строке одинаковое количество элементов.
Строки и столбцы нумеруются с нуля. Решай, как удобно: циклами или генераторами.

1. Сумма всех элементов

Дана матрица:
matrix = [[1, 2, 3],
          [4, 5, 6],
          [7, 8, 9]]

Найди сумму всех её элементов и выведи её.

Ожидаемый вывод:
45
'''
matrix = [[1, 2, 3],
          [4, 5, 6],
          [7, 8, 9]]

'''
2. Больше заданного числа

Даны матрица и число:
matrix = [[5, 12, 7],
          [3, 9, 15],
          [10, 1, 8]]
k = 7

Посчитай, сколько элементов матрицы строго больше k, и выведи это количество.

Ожидаемый вывод:
5
'''
matrix = [[5, 12, 7],
          [3, 9, 15],
          [10, 1, 8]]
k = 7

'''
3. Минимальный элемент

Дана матрица:
matrix = [[4, -2, 7],
          [0, 5, -6],
          [3, 8, 1]]

Найди минимальный элемент матрицы и выведи его.

Ожидаемый вывод:
-6
'''
matrix = [[4, -2, 7],
          [0, 5, -6],
          [3, 8, 1]]

'''
4. Сумма каждой строки

Дана матрица:
matrix = [[2, 4, 6],
          [1, 1, 1],
          [5, 0, 5]]

Составь список, где каждый элемент — сумма соответствующей строки, и выведи его.

Ожидаемый вывод:
[12, 3, 10]
'''
matrix = [[2, 4, 6],
          [1, 1, 1],
          [5, 0, 5]]

'''
5. Строка с максимальной суммой

Дана матрица:
matrix = [[3, 1, 4],
          [9, 0, 0],
          [2, 6, 1],
          [1, 5, 3]]

Найди индекс строки с наибольшей суммой элементов и выведи его.
Если таких строк несколько, выведи индекс первой из них.

Ожидаемый вывод:
1
'''
matrix = [[3, 1, 4],
          [9, 0, 0],
          [2, 6, 1],
          [1, 5, 3]]

'''
6. Сумма каждого столбца

Дана матрица:
matrix = [[1, 2, 3],
          [4, 5, 6]]

Составь список сумм по столбцам: первый элемент — сумма первого столбца, второй — второго и так далее.
Выведи этот список.

Ожидаемый вывод:
[5, 7, 9]

Пригодится: range(len(matrix[0]))
'''
matrix = [[1, 2, 3],
          [4, 5, 6]]

'''
7. Есть ли элемент

Даны матрица и список чисел, которые нужно найти:
matrix = [[3, 8, 1],
          [6, 2, 9]]
targets = [9, 7]

Для каждого числа из targets выведи True, если оно есть в матрице, иначе False.
Каждый ответ — на отдельной строке.

Ожидаемый вывод:
True
False
'''
matrix = [[3, 8, 1],
          [6, 2, 9]]
targets = [9, 7]

'''
8. Строки с нулём

Дана матрица:
matrix = [[1, 0, 3],
          [4, 5, 6],
          [0, 0, 7],
          [8, 9, 0]]

Посчитай, сколько строк содержат хотя бы один 0, и выведи это количество.
Строка с несколькими нулями считается один раз.

Ожидаемый вывод:
3
'''
matrix = [[1, 0, 3],
          [4, 5, 6],
          [0, 0, 7],
          [8, 9, 0]]

'''
9. Больше всего чётных

Дана матрица:
matrix = [[1, 3, 5, 2],
          [2, 4, 7, 9],
          [6, 1, 8, 3],
          [2, 2, 1, 1]]

Найди индекс строки, в которой больше всего чётных элементов, и выведи его.
Если таких строк несколько, выведи индекс первой из них.

Ожидаемый вывод:
1
'''
matrix = [[1, 3, 5, 2],
          [2, 4, 7, 9],
          [6, 1, 8, 3],
          [2, 2, 1, 1]]

'''
10. Все строки возрастают?

Даны две матрицы:
a = [[1, 2, 3],
     [0, 5, 9],
     [-3, -1, 4]]
b = [[1, 2, 3],
     [4, 4, 6],
     [7, 8, 9]]

Для каждой матрицы проверь, что в каждой её строке элементы строго возрастают слева направо:
каждый следующий больше предыдущего. Выведи True или False: сначала для a, потом для b.

Ожидаемый вывод:
True
False
'''
a = [[1, 2, 3],
     [0, 5, 9],
     [-3, -1, 4]]
b = [[1, 2, 3],
     [4, 4, 6],
     [7, 8, 9]]
