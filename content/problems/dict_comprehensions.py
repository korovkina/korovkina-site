'''
Задачи на генераторы словарей (dict comprehension). Каждую задачу реши одним генератором словаря — одной строкой.

Полезные ссылки:
1. Методы словарей: https://www.w3schools.com/python/python_ref_dictionary.asp
2. Генераторы словарей в документации Python: https://docs.python.org/3/tutorial/datastructures.html#dictionaries

Напоминание:
    {ключ: значение for x in список if условие}
    {k: v for k, v in словарь.items() if условие}     — фильтр по парам словаря

1. Квадраты чисел

Дан список:
nums = [1, 2, 3, 4]

Составь словарь: число → его квадрат. Выведи словарь.

Ожидаемый вывод:
{1: 1, 2: 4, 3: 9, 4: 16}
'''
nums = [1, 2, 3, 4]

'''
2. Длины слов

Дан список:
words = ["cat", "banana", "hi"]

Составь словарь: слово → длина слова. Выведи словарь.

Ожидаемый вывод:
{'cat': 3, 'banana': 6, 'hi': 2}
'''
words = ["cat", "banana", "hi"]

'''
3. Только чётные значения

Дан словарь:
d = {"a": 1, "b": 4, "c": 7, "d": 8}

Составь новый словарь только из тех пар, где значение чётное. Выведи его.

Ожидаемый вывод:
{'b': 4, 'd': 8}

Пригодится: dict.items()
'''
d = {"a": 1, "b": 4, "c": 7, "d": 8}

'''
4. Ключи заглавными буквами

Дан словарь:
cities = {"russia": "Moscow", "france": "Paris"}

Составь новый словарь, где ключи записаны в верхнем регистре, а значения остались без изменений. Выведи его.

Ожидаемый вывод:
{'RUSSIA': 'Moscow', 'FRANCE': 'Paris'}

Пригодится: str.upper()
'''
cities = {"russia": "Moscow", "france": "Paris"}

'''
5. Только строковые значения

Дан словарь:
data = {"a": 1, "b": "hello", "c": "python", "d": 3}

Составь новый словарь только из тех пар, где значение — строка. Выведи его.

Ожидаемый вывод:
{'b': 'hello', 'c': 'python'}

Пригодится: isinstance(значение, str)
'''
data = {"a": 1, "b": "hello", "c": "python", "d": 3}

'''
6. Ключ и значение меняются местами

Дан словарь:
d = {"cat": 3, "dog": 5, "bird": 2}

Составь словарь, в котором ключи и значения поменялись местами. Выведи его.

Ожидаемый вывод:
{3: 'cat', 5: 'dog', 2: 'bird'}
'''
d = {"cat": 3, "dog": 5, "bird": 2}

'''
7. Слово → первая буква

Дан список:
words = ["apple", "cat", "dog", "banana"]

Составь словарь: слово → его первая буква. Выведи его.

Ожидаемый вывод:
{'apple': 'a', 'cat': 'c', 'dog': 'd', 'banana': 'b'}
'''
words = ["apple", "cat", "dog", "banana"]

'''
8. Квадраты чисел больше 10

Дан список:
nums = [3, 15, 8, 20, 11]

Составь словарь: число → его квадрат, но только для чисел больше 10. Выведи его.

Ожидаемый вывод:
{15: 225, 20: 400, 11: 121}
'''
nums = [3, 15, 8, 20, 11]

'''
9. Плоский словарь из вложенного

Дан вложенный словарь:
users = {
    "anna": {"age": 14, "city": "Moscow"},
    "ivan": {"age": 15, "city": "SPB"},
    "olga": {"age": 14, "city": "Kazan"}
}

Составь словарь: имя → город. Город достань из вложенного словаря по ключу "city". Выведи результат.

Ожидаемый вывод:
{'anna': 'Moscow', 'ivan': 'SPB', 'olga': 'Kazan'}
'''
users = {
    "anna": {"age": 14, "city": "Moscow"},
    "ivan": {"age": 15, "city": "SPB"},
    "olga": {"age": 14, "city": "Kazan"}
}

'''
10. Продажи популярных товаров

Дан список сделок: кто из менеджеров продал и сколько штук каждого товара.
sales = [
    {"manager": "Anna", "items": {"pen": 4, "notebook": 2, "pencil": 10}},
    {"manager": "Olga", "items": {"pen": 1, "folder": 5}},
    {"manager": "Ivan", "items": {"notebook": 7, "pencil": 3, "pen": 2}},
    {"manager": "Egor", "items": {"pencil": 6, "folder": 2}},
]

Назовём товар популярным, если хотя бы в одной сделке его продали 5 штук или больше. Здесь это pencil, folder и notebook, а pen — нет.
Составь словарь: имя менеджера → сколько всего штук популярных товаров он продал. В словаре должны быть все четыре менеджера.
Сначала найди множество популярных товаров (тоже генератором), затем одним генератором словаря посчитай ответ.

Ожидаемый вывод:
{'Anna': 12, 'Olga': 5, 'Ivan': 10, 'Egor': 8}

Пригодится: генератор множества {x for ...}, sum() с генератором внутри, dict.items()
'''
sales = [
    {"manager": "Anna", "items": {"pen": 4, "notebook": 2, "pencil": 10}},
    {"manager": "Olga", "items": {"pen": 1, "folder": 5}},
    {"manager": "Ivan", "items": {"notebook": 7, "pencil": 3, "pen": 2}},
    {"manager": "Egor", "items": {"pencil": 6, "folder": 2}},
]
